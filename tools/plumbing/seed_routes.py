#!/usr/bin/env python3
"""One-time seed of data/plumbing/routes.json – the single source of truth for the pipe routes of the PROPOSAL,
shared by the 2D plan editor (editor.html) and (from editor stage 4) the 3D model.

Input: data/plumbing/proposal.json (generated by propose*.py). Each run keeps its own pts3d [E, N, H], simplified to its
turning points (Douglas–Peucker in 3D, tolerance TOL_M; the largest deviation per run is stored in run.simplify and in
the verification table). The consultant's network (network.json) is NOT copied: it stays a read-only reference layer.

After the seed, routes.json is edited by the editor only. Re-running this script OVERWRITES manual edits, so it refuses
when routes.json already holds edits (status 'manual' anywhere) unless --force is given.
"""
import json, math, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
J = lambda p: json.load(open(os.path.join(ROOT, p), encoding='utf-8'))
OUT = os.path.join(ROOT, 'data', 'plumbing', 'routes.json')
SRC = 'data/plumbing/proposal.json'
TOL_M = 0.01
r3 = lambda v: round(float(v), 3)


def seg_dist(p, a, b):
    p, a, b = p[:3], a[:3], b[:3]
    ab = [b[i] - a[i] for i in range(3)]; ap = [p[i] - a[i] for i in range(3)]
    L2 = sum(c * c for c in ab)
    t = 0 if L2 == 0 else max(0, min(1, sum(ap[i] * ab[i] for i in range(3)) / L2))
    return math.dist(p, [a[i] + t * ab[i] for i in range(3)])


def dp(P, tol):
    if len(P) < 3: return list(P)
    d, k = max((seg_dist(P[i], P[0], P[-1]), i) for i in range(1, len(P) - 1))
    if d <= tol: return [P[0], P[-1]]   # points carry their source index as 4th item
    return dp(P[:k + 1], tol)[:-1] + dp(P[k:], tol)


def simplify(P):
    # H = None ("by the ground surface", network.json convention) -> simplified in plan only, None kept on the kept points
    flat = any(p[2] is None for p in P)
    X = [[p[0], p[1], 0.0 if flat else p[2], i] for i, p in enumerate(P)]
    X = [x for i, x in enumerate(X) if i == 0 or math.dist(x[:3], X[i - 1][:3]) > 1e-4]
    Q = dp([x[:3] + [x[3]] for x in X], TOL_M)
    dev = max(min(seg_dist(x[:3], Q[j][:3], Q[j + 1][:3]) for j in range(len(Q) - 1)) for x in X) if len(Q) > 1 else 0
    V = [[r3(P[q[3]][0]), r3(P[q[3]][1]), None if P[q[3]][2] is None else r3(P[q[3]][2])] for q in Q]
    return V, {'tol_m': TOL_M, 'ptsBefore': len(X), 'ptsAfter': len(Q), 'maxDev_m': r3(dev), **({'plan': True} if flat else {})}


def floor_of_id(rid, default=None):
    return rid.split('@')[1] if '@' in rid else default


def main():
    if os.path.exists(OUT) and '--force' not in sys.argv:
        cur = json.load(open(OUT, encoding='utf-8'))
        if any(r.get('status') == 'manual' or r.get('edited') for r in cur.get('runs', [])):
            sys.exit('routes.json already holds manual edits – not overwriting (use --force to discard them)')
    P = J(SRC); FG = J('data/structure/floor-ground.json'); H0 = J('data/site/origin.json')['H0']
    # house axes: the same frame the proposal is routed in (tools/plumbing/proposal_common.py: ממ"ד edge, K-31)
    c = (FG['ceiling']['openings'] or FG['ceiling']['mamad'])[0]['footprintITM']
    ux = (-(c[2][0] - c[1][0]), -(c[2][1] - c[1][1])); l = math.hypot(*ux); ux = (ux[0] / l, ux[1] / l); uy = (-ux[1], ux[0])
    runs, nodes = [], []

    def add_run(r, path, system=None, floor=None, kind='run', extra=None):
        V, simp = simplify(r['pts3d'])
        rec = {'id': r['id'], 'kind': kind, 'system': system or r['system'], 'floor': floor or r.get('floor') or floor_of_id(r['id'], 'site'),
               'D_mm': r.get('D_mm'), 'material': r.get('material'), 'from': r.get('from'), 'to': r.get('to'), 'vertices': V}
        for k in ('slope', 'ILup', 'ILdown', 'insulation_mm', 'conduitD_mm', 'replaces', 'note'):
            if r.get(k) is not None: rec[k] = r[k]
        rec.update(extra or {})
        rec.update({'status': r.get('status', 'proposal'), 'source': f'{SRC} → {path} {r["id"]}', 'simplify': simp})
        runs.append(rec)

    for r in P['runs']: add_run(r, 'runs')
    for r in P['unitSewer']['runs']: add_run(r, 'unitSewer.runs')
    for r in P['firstFloor']['runs']: add_run(r, 'firstFloor.runs')
    for r in P['site']['runs']: add_run(r, 'site.runs')
    for r in P['site']['drops']: add_run({**r, 'from': r.get('run'), 'to': r.get('chamber')}, 'site.drops', system='sewage', floor='site', kind='drop')
    for s in P['stackMoves']:
        if not s.get('pts3d'): continue
        add_run(s, 'stackMoves', system='sewage', floor='ground', kind='stack', extra={'stack': s['stack']})
        for k, cn in enumerate(s.get('connectors') or []):   # short pieces from the moved stack to the existing branch
            fl = cn['run'].split('@')[1] if '@' in cn['run'] else 'ground'
            add_run({**cn, 'id': f"{s['id']}-C{k + 1}", 'from': cn['run'], 'to': s['id'], 'status': s.get('status', 'proposal')},
                    f"stackMoves[{s['id']}].connectors[{k}]", system='sewage', floor=fl, kind='connector')
    alt = next(a for a in P['rain']['alternatives'] if a['id'] == P['rain']['default'])
    for r in alt['runs']: add_run(r, f'rain.alternatives[{alt["id"]}].runs', system='rain', extra={'alternative': alt['id']})

    LV = sorted((f['level'], f['id']) for f in J('data/config/tags.json')['floors'] if f.get('level') is not None)

    def floor_by_H(h):  # floor whose level (data/config/tags.json) is the highest one at or below the node (+5 cm)
        return [fid for lv, fid in LV if lv <= h - H0 + 0.05][-1]

    def add_node(n, path, kind=None, H=None):
        hh = H if H is not None else n.get('H')
        rec = {'id': n['id'], 'kind': kind or n.get('kind'), 'floor': n.get('floor') or floor_of_id(n['id']) or floor_by_H(hh), 'E': r3(n['E']), 'N': r3(n['N']),
               'H': r3(H if H is not None else n['H']) if (H is not None or n.get('H') is not None) else None, 'title': n.get('title')}
        for k in ('D_mm', 'cold', 'hot', 'fixture'):
            if n.get(k) is not None: rec[k] = n[k]
        rec.update({'status': n.get('status', 'proposal'), 'source': f'{SRC} → {path} {n["id"]}'})
        nodes.append(rec)

    for n in P['points']: add_node(n, 'points')
    for m in P['manifolds']:
        add_node(m, 'manifolds', kind='manifold', H=(m.get('H_floor') if m.get('H_floor') is not None else None))
        # body of the manifold: axis / face and every outlet (plan position, destination, diameter), heights above the floor
        nodes[-1].update({'axis': m['axis'], 'face': m['face'], 'coldH': m.get('coldH'), 'hotH': m.get('hotH'), 'hotPending': m.get('hotPending'),
                          'outlets': {k: [{'E': r3(o['E']), 'N': r3(o['N']), 'to': o['to'], 'D_mm': o.get('D_mm')} for o in v] for k, v in m['outlets'].items()}})
    for h in P['unitHot']['heaters']: add_node(h, 'unitHot.heaters', kind='heater')
    for key, kind in (('submeters', 'meter'), ('mainValve', 'valve'), ('recircPump', 'pump')):
        if P.get(key): add_node({**P[key], 'id': key}, key, kind=kind)

    ch = P['unitSewer']['chamber']
    add_node({'id': ch['id'], 'E': ch['E'], 'N': ch['N'], 'H': ch['TL'], 'title': 'תא שאיבה לשפכי היחידות (T.L)', 'floor': 'site'}, 'unitSewer.chamber', kind='pumpChamber')
    hr = P['site']['hoseReel']
    add_node({'id': hr['id'], 'E': hr['E'], 'N': hr['N'], 'H': None, 'title': 'גלגלון כיבוי', 'floor': 'site'}, 'site.hoseReel', kind='hoseReel')
    mt = P['site']['meter']
    add_node({'id': 'UT-W', 'E': mt['utw'][0], 'N': mt['utw'][1], 'H': None, 'title': 'קצה הכנת המים של התאגיד', 'floor': 'site'}, 'site.meter.utw', kind='utilityWater')
    out = {
        '_doc': 'מקור האמת לתוואי הצנרת של ההצעה – משותף לעורך הדו-ממדי (editor.html) ולמודל. vertices = נקודות פנייה [E, N, H] '
                'ב-ITM, H מוחלט (מרכז הצינור; בביוב – כמו ב-pts3d של ההצעה). נזרע פעם אחת ע"י tools/plumbing/seed_routes.py, '
                'ומאז נערך רק בעורך (status: manual + edited). צנרת היועץ (network.json) לא כאן – שכבת קריאה בלבד.',
        'version': 1,
        'seededFrom': SRC,
        'frame': {'origin': [r3(c[1][0]), r3(c[1][1])], 'ux': [r3(ux[0] * 1e6) / 1e6, r3(ux[1] * 1e6) / 1e6], 'uy': [r3(uy[0] * 1e6) / 1e6, r3(uy[1] * 1e6) / 1e6],
                  'azimuthDeg_ux': round(math.degrees(math.atan2(ux[0], ux[1])) % 360, 3),
                  'source': 'data/structure/floor-ground.json ceiling.mamad[0] – פינה [1] וצלע [1]→[2] של הממ"ד (אותם צירים של tools/plumbing/proposal_common.py)'},
        'H0': H0,
        'superseded': {'runs': sorted(set(P['superseded'] + P['firstFloor']['superseded'] + P['site']['superseded'] + P['unitSewer']['superseded'])),
                       'source': f'{SRC} superseded, firstFloor.superseded, site.superseded, unitSewer.superseded'},
        'nodes': nodes,
        'runs': runs,
    }
    json.dump(out, open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    devs = [r['simplify']['maxDev_m'] for r in runs]
    print(f'wrote data/plumbing/routes.json: {len(runs)} runs, {len(nodes)} nodes; vertices {sum(r["simplify"]["ptsBefore"] for r in runs)} → '
          f'{sum(r["simplify"]["ptsAfter"] for r in runs)}; max deviation {max(devs):.4f} m')


if __name__ == '__main__':
    main()
