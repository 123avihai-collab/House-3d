#!/usr/bin/env python3
"""Pile bearing check: what sits on each pile head, and the vertical gap to it.

For every pile (data/structure/piles.json) the elements whose plan footprint covers the pile centre are collected –
ground beams and pile caps (framing.json), basement walls (framing.json), perimeter footings (perimeter.json) – and
the gap = (lowest bottom among them) − pile head is computed. A pile with a gap above the tolerance has nothing
bearing on its head (open-issues: pile 27). Piles with no element above are reported apart (pool piles 28–32, #193).
Nothing is changed in the geometry – this only flags.

Output: data/structure/pile-bearing.json.  Run after extract_framing.py / extract_perimeter.py.
"""
import json, os
from shapely.geometry import Point, Polygon, LineString

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda p: json.load(open(os.path.join(ROOT, p), encoding='utf-8'))
TOL = 0.05   # m – pile head within 5 cm below the element bottom counts as bearing (cf. pile 8 / B-53, #28)
piles = J('data/structure/piles.json')['piles']
F = J('data/structure/framing.json'); PER = J('data/structure/perimeter.json')

els = []
for b in F['groundBeams']:
    if b.get('axisITM') and b.get('bottomRel') is not None:
        els.append((b['id'], 'beam', LineString(b['axisITM']).buffer(b['width_m'] / 2, cap_style=2), b['bottomRel']))
for c in F.get('pileCaps', []): els.append((c['id'], 'cap', Polygon(c['ringITM']), c['bottomRel']))
for w in F['basementWalls']:
    for part in (w.get('partsITM') or [{'ringITM': w['footprintITM']}]):
        els.append((w['id'], 'basementWall', Polygon(part['ringITM']).buffer(0), part.get('bottomRel', w['bottomRel'])))
for ft in PER['footings']: els.append((ft['id'], 'footing', Polygon(ft['ringITM']).buffer(0), ft['bottomRel']))

out = []
for p in piles:
    c = Point(p['E'], p['N']); r = p['diameter_m'] / 2
    hit = [(i, k, b) for i, k, g, b in els if g.distance(c) < r * 0.5]
    rec = {'id': p['id'], 'headRel': p['headRel'], 'above': [{'id': i, 'kind': k, 'bottomRel': b} for i, k, b in hit]}
    if not hit: rec['status'] = 'nothing'
    else:
        low = min(b for *_, b in hit); rec['gap_m'] = round(low - p['headRel'], 3)
        rec['status'] = 'gap' if rec['gap_m'] > TOL else 'ok'
    out.append(rec)
gaps = [r for r in out if r['status'] == 'gap']
res = {'_doc': 'Generated by tools/check_pile_bearing.py – do not edit. status: ok | gap (nothing bears on the head) | nothing (no element above in the data)',
       'tolerance_m': TOL, 'gaps': [r['id'] for r in gaps], 'nothingAbove': [r['id'] for r in out if r['status'] == 'nothing'], 'piles': out,
       'source': 'data/structure/piles.json (K-400) × framing.json (K-11 / K-12 / K-21 / K-22) × perimeter.json'}
json.dump(res, open(os.path.join(ROOT, 'data/structure/pile-bearing.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
for r in gaps: print('GAP', r)
print('nothing above:', res['nothingAbove'])
